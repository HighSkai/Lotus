<#
.SYNOPSIS
  Downloads the pinned sing-box engine and rule-set used by LOTUS and verifies
  their SHA-256 digests before placing them in app/src-tauri/binaries.

  Nothing is executed from the download. If a digest does not match, the script
  stops and leaves no file behind.

  To upgrade the engine: change $EngineVersion and $EngineSha256 (take the digest
  from the GitHub release asset, e.g. `gh release view v1.14.4 -R SagerNet/sing-box --json assets`),
  then re-run and execute the test suite (`cargo test -p lotus-core` validates every
  generated configuration with `sing-box check`).
#>
[CmdletBinding()]
param(
  [switch]$Force
)
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

$EngineVersion = '1.14.4'
$EngineSha256  = '99185d75d314a07dbba4a130c8ad986cbeb629a07927975636b341ca61f991df'
$EngineUrl     = "https://github.com/SagerNet/sing-box/releases/download/v$EngineVersion/sing-box-$EngineVersion-windows-amd64.zip"

# Tracker/ads rule-set, pinned to a commit of SagerNet/sing-geosite (branch "rule-set").
$RuleSetCommit = '23066e3b0833d1484916637dde2b5bae80178045'
$RuleSetUrl    = "https://raw.githubusercontent.com/SagerNet/sing-geosite/$RuleSetCommit/geosite-category-ads-all.srs"
$RuleSetSha256 = ''   # filled on first fetch; see vendor/LOCK

$Root     = Split-Path -Parent $PSScriptRoot
$BinDir   = Join-Path $Root 'app\src-tauri\binaries'
$ResDir   = Join-Path $Root 'app\src-tauri\resources'
$LockFile = Join-Path $Root 'vendor\LOCK'
$Triple   = 'x86_64-pc-windows-msvc'
$EngineOut = Join-Path $BinDir "sing-box-$Triple.exe"

New-Item -ItemType Directory -Force $BinDir, $ResDir, (Split-Path $LockFile) | Out-Null

function Get-Sha256([string]$Path) { (Get-FileHash -Algorithm SHA256 -LiteralPath $Path).Hash.ToLowerInvariant() }

$lock = @{}
if (Test-Path $LockFile) {
  Get-Content $LockFile | Where-Object { $_ -match '^\s*([^#=\s]+)\s*=\s*(\S+)' } | ForEach-Object { $lock[$Matches[1]] = $Matches[2] }
}

# --- engine --------------------------------------------------------------
if ($Force -or -not (Test-Path $EngineOut) -or $lock['engine.exe.sha256'] -ne (Get-Sha256 $EngineOut)) {
  $tmp = Join-Path ([IO.Path]::GetTempPath()) ("lotus-engine-" + [guid]::NewGuid())
  New-Item -ItemType Directory $tmp | Out-Null
  try {
    $zip = Join-Path $tmp 'engine.zip'
    Write-Host "Downloading sing-box $EngineVersion ..."
    Invoke-WebRequest -UseBasicParsing -Uri $EngineUrl -OutFile $zip
    $got = Get-Sha256 $zip
    if ($got -ne $EngineSha256) { throw "sing-box archive digest mismatch: expected $EngineSha256, got $got" }
    Write-Host "  archive SHA-256 verified"
    Expand-Archive -LiteralPath $zip -DestinationPath (Join-Path $tmp 'x')
    $exe = Get-ChildItem -Recurse (Join-Path $tmp 'x') -Filter 'sing-box.exe' | Select-Object -First 1
    if (-not $exe) { throw 'sing-box.exe not found in archive' }
    Copy-Item $exe.FullName $EngineOut -Force
    $extra = Get-ChildItem -Recurse (Join-Path $tmp 'x') -Filter '*.dll'
    foreach ($d in $extra) { Copy-Item $d.FullName (Join-Path $ResDir $d.Name) -Force; Write-Host "  bundled $($d.Name)" }
    $lic = Get-ChildItem -Recurse (Join-Path $tmp 'x') -Filter 'LICENSE*' | Select-Object -First 1
    if ($lic) { Copy-Item $lic.FullName (Join-Path $ResDir 'SING-BOX-LICENSE.txt') -Force }
    $lock['engine.version'] = $EngineVersion
    $lock['engine.zip.sha256'] = $EngineSha256
    $lock['engine.exe.sha256'] = Get-Sha256 $EngineOut
  } finally {
    Remove-Item -Recurse -Force $tmp -ErrorAction SilentlyContinue
  }
} else {
  Write-Host "sing-box $EngineVersion already present and verified"
}

# --- tracker rule-set ----------------------------------------------------
$RuleOut = Join-Path $ResDir 'block-trackers.srs'
$expectedRule = if ($RuleSetSha256) { $RuleSetSha256 } else { $lock['ruleset.sha256'] }
if ($Force -or -not (Test-Path $RuleOut) -or ($expectedRule -and (Get-Sha256 $RuleOut) -ne $expectedRule)) {
  $tmpRule = Join-Path ([IO.Path]::GetTempPath()) ("lotus-rules-" + [guid]::NewGuid() + '.srs')
  Write-Host "Downloading tracker rule-set @ $($RuleSetCommit.Substring(0,10)) ..."
  Invoke-WebRequest -UseBasicParsing -Uri $RuleSetUrl -OutFile $tmpRule
  $got = Get-Sha256 $tmpRule
  if ($expectedRule -and $got -ne $expectedRule) { Remove-Item $tmpRule -Force; throw "rule-set digest mismatch: expected $expectedRule, got $got" }
  Move-Item $tmpRule $RuleOut -Force
  $lock['ruleset.commit'] = $RuleSetCommit
  $lock['ruleset.sha256'] = $got
}

$lines = @('# Generated by scripts/fetch-engine.ps1. Commit this file; it pins vendor digests.')
foreach ($k in ($lock.Keys | Sort-Object)) { $lines += "$k = $($lock[$k])" }
Set-Content -LiteralPath $LockFile -Value $lines -Encoding utf8
Write-Host "Done. Engine: $EngineOut"
